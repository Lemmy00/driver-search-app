const dictionaries: Record<Locale, Messages> = {
  en,
  fr,
  de,
  it,
  es,
  "sr-Latn": srLatn
};

type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
  translateValue: (namespace: ValueNamespace, value: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function resolveLocale(value: string | null | undefined): Locale | null {
  if (!value) {
    return null;
  }

  const normalized = value.toLowerCase().replace("_", "-");
  if (normalized === "sr" || normalized.startsWith("sr-")) {
    return "sr-Latn";
  }

  const match = supportedLocales.find((locale) => locale.code.toLowerCase() === normalized);
  if (match) {
    return match.code;
  }

  const languageMatch = supportedLocales.find((locale) => normalized.startsWith(locale.code.toLowerCase()));
  return languageMatch?.code ?? null;
}

function initialLocale(): Locale {
  if (typeof window === "undefined") {
    return "en";
  }

  const stored = resolveLocale(window.localStorage.getItem(localeStorageKey));
  if (stored) {
    return stored;
  }

  for (const language of window.navigator.languages ?? [window.navigator.language]) {
    const resolved = resolveLocale(language);
    if (resolved) {
      return resolved;
    }
  }

  return "en";
}

function interpolate(message: string, values: Record<string, string | number> | undefined): string {
  if (!values) {
    return message;
  }

  return message.replace(/\{\{(\w+)\}\}/g, (_, key: string) =>
    values[key] === undefined ? "" : String(values[key])
  );
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale);

  useEffect(() => {
    document.documentElement.lang = locale;
    window.localStorage.setItem(localeStorageKey, locale);
  }, [locale]);

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale: setLocaleState,
      t: (key, values) => interpolate(dictionaries[locale][key], values),
      translateValue: (namespace, value) => {
        const map = valueKeyMaps[namespace] as Partial<Record<string, TranslationKey>>;
        const key = map[value];
        return key ? dictionaries[locale][key] : value;
      }
    }),
    [locale]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext);
  if (!value) {
    throw new Error("useI18n must be used inside I18nProvider");
  }
  return value;
}
